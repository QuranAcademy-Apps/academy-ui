/// Primary categories describe purpose. Source apps are scenario tags only.
enum ComponentCategory {
  actions('Кнопки', AcademySymbols.play),
  input('Текстовый ввод', AcademySymbols.filters),
  selection('Выбор значений', AcademySymbols.filters),
  dates('Дата и время', AcademySymbols.book),
  containers('Таблицы и карточки', AcademySymbols.checklist),
  navigation('Навигация', AcademySymbols.upDown),
  overlays('Меню и окна', AcademySymbols.expand),
  presentation('Данные и медиа', AcademySymbols.book),
  help('Подсказки', AcademySymbols.info),
  feedback('Статус и прогресс', AcademySymbols.info),
  foundations('Тема и эффекты', AcademySymbols.sun);

  const ComponentCategory(this.title, this.icon);
  final String title;
  final IconData icon;
}

/// Stable ID, canonical API, one primary category and contextual references.
/// Add a descriptor and its demo together when introducing a new family.
class ComponentDescriptor {
  const ComponentDescriptor(
    this.id,
    this.title,
    this.category,
    this.apis,
    this.purpose, {
    this.related = const [],
    this.scenarios = const [],
    this.states = const ['Светлая / тёмная тема', 'Крупный текст', 'RTL'],
  });
  final String id, title, purpose;
  final ComponentCategory category;
  final List<String> apis, related, scenarios, states;
  bool matches(String query) => [
    title,
    purpose,
    ...apis,
  ].join(' ').toLowerCase().contains(query.trim().toLowerCase());
}

